router = APIRouter(prefix="/dev", tags=["dev"])


class DevCompileRequest(BaseModel):
    ir: SlideIR
    asset_dims: dict[str, tuple[int, int]] = Field(default_factory=dict)


@router.post("/compile", response_model=CompileResult)
async def dev_compile(req: DevCompileRequest) -> CompileResult:
    if settings.ENV != "dev":
        raise BadRequestError(
            code="dev_only", message="Dev endpoints are only available in ENV=dev"
        )
    ctx = CompileCtx(asset_dims=req.asset_dims)
    return compile(req.ir, ctx)


@router.post("/slides/{slide_id}/apply-ir")
async def dev_apply_ir(
    slide_id: Path | str,
    req: DevCompileRequest,
    db: AsyncSession = Depends(get_db),
):
    import uuid

    if settings.ENV != "dev":
        raise BadRequestError(
            code="dev_only", message="Dev endpoints are only available in ENV=dev"
        )

    try:
        slide_uuid = uuid.UUID(str(slide_id))
    except ValueError:
        raise BadRequestError("invalid_uuid", f"Invalid slide ID '{slide_id}'") from None

    stmt = select(Slide).where(Slide.id == slide_uuid, Slide.deleted_at.is_(None))
    res = await db.execute(stmt)
    slide = res.scalar_one_or_none()
    if not slide:
        raise NotFoundError("slide_not_found", f"Slide {slide_uuid} not found")

    ctx = CompileCtx(asset_dims=req.asset_dims)
    comp_res = compile(req.ir, ctx)
    if comp_res.skeleton is None or comp_res.errors:
        raise BadRequestError("compilation_failed", "; ".join(comp_res.errors))

    seq_stmt = select(func.coalesce(func.max(SlideVersion.seq), 0)).where(
        SlideVersion.slide_id == slide_uuid
    )
    max_seq = (await db.execute(seq_stmt)).scalar_one()

    new_version = SlideVersion(
        slide_id=slide_uuid,
        seq=max_seq + 1,
        origin="manual",
        summary=req.ir.title or "Applied IR from Dev Compiler",
        ir=req.ir.model_dump(),
        skeleton=comp_res.skeleton,
        scene=None,
        warnings=comp_res.warnings,
    )
    db.add(new_version)
    await db.flush()

    slide.current_version_id = new_version.id
    slide.draft_scene = None
    slide.draft_hash = None
    slide.status = "ready"
    await db.commit()

    return {
        "status": "ok",
        "slide_id": str(slide.id),
        "version_id": str(new_version.id),
        "warnings": comp_res.warnings,
        "stats": comp_res.stats.model_dump(),
    }



def _generate_sample_png() -> bytes:
    img = Image.new("RGBA", (640, 480), color=(240, 244, 248, 255))
    draw = ImageDraw.Draw(img)

    # Draw decorative shapes
    draw.rounded_rectangle([40, 40, 600, 440], radius=20, outline=(25, 113, 194, 255), width=4)
    draw.ellipse(
        [80, 80, 240, 240], fill=(165, 216, 255, 200), outline=(25, 113, 194, 255), width=2
    )
    draw.rectangle(
        [300, 100, 560, 220], fill=(255, 236, 153, 220), outline=(240, 140, 0, 255), width=2
    )
    draw.rounded_rectangle(
        [100, 280, 540, 400],
        radius=12,
        fill=(178, 242, 187, 200),
        outline=(47, 158, 68, 255),
        width=2,
    )

    # Simple text lines if default font is available
    draw.text((120, 320), "Sample Visual Asset (Generated by Backend)", fill=(30, 30, 30, 255))

    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


@router.post("/decks/sample", response_model=DeckRead, status_code=status.HTTP_201_CREATED)
async def create_sample_deck(db: AsyncSession = Depends(get_db)) -> DeckRead:
    if settings.ENV != "dev":
        raise BadRequestError(
            code="dev_only", message="Dev endpoints are only available in ENV=dev"
        )

    # 1. Create Sample Deck
    deck = Deck(
        title="Excalidraw Slide Studio Demo Deck",
        status="ready",
        settings=DeckSettings(
            slide_count=4,
            tone="professional",
            diagram_intensity="medium",
            density="standard",
            audience="General Developers & Designers",
        ).model_dump(),
    )
    db.add(deck)
    await db.flush()

    fixtures_dir = Path(__file__).parent.parent / "fixtures"

    # 2. Generate PNG asset for image slide
    png_bytes = _generate_sample_png()
    png_file_id = hashlib.sha1(png_bytes).hexdigest()
    asset = await save_asset(
        db=db,
        storage=storage,
        deck_id=deck.id,
        file_id=png_file_id,
        data=png_bytes,
        mime="image/png",
    )

    # 3. Load fixtures
    fixture_files = [
        ("cover.json", "Cover Slide"),
        ("bullets.json", "Architecture Highlights"),
        ("diagram.json", "Generation Pipeline Architecture"),
        ("image.json", "Visual Assets"),
    ]

    for pos, (filename, summary) in enumerate(fixture_files):
        fixture_path = fixtures_dir / filename
        skeleton_content = json.loads(fixture_path.read_text(encoding="utf-8"))

        # Inject asset id if this is the image slide
        if filename == "image.json":
            for el in skeleton_content.get("elements", []):
                if el.get("type") == "image":
                    el["fileId"] = asset.id
            skeleton_content["asset_ids"] = [asset.id]

        slide = Slide(
            deck_id=deck.id,
            position=pos,
            status="ready",
            draft_rev=0,
        )
        db.add(slide)
        await db.flush()

        v1 = SlideVersion(
            slide_id=slide.id,
            seq=1,
            origin="manual",
            summary=summary,
            skeleton=skeleton_content,
            scene=None,  # Browser will normalize into scene on first load
            warnings=[],
        )
        db.add(v1)
        await db.flush()

        slide.current_version_id = v1.id

    await db.commit()
    await db.refresh(deck)

    return DeckRead(
        id=deck.id,
        title=deck.title,
        status=deck.status,
        settings=DeckSettings(**deck.settings),
        current_plan_id=deck.current_plan_id,
        slide_count=4,
        created_at=deck.created_at,
        updated_at=deck.updated_at,
    )
